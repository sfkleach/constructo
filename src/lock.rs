//! The lock file, `constructo.lock`, as specified in `docs/specs/lock-file-format.md`.
//!
//! It records a digest for each project that is loaded, other than the root project and the built-in ones, and a digest
//! for each file of the project. This module reads and writes the file. Finding the files of a project and comparing
//! the digests with them is done elsewhere.

use crate::diagnostics::{Diagnostic, Pos};
use crate::digest::{is_digest, project_digest};
use crate::fetch::{is_commit, redact, validate_url};
use crate::project::check_name;
use serde::Deserialize;
use std::collections::BTreeMap;
use toml::Spanned;

/// The name of the lock file, in the root of the project.
pub const LOCK_FILE: &str = "constructo.lock";

/// The version of the format that is read and written.
pub const VERSION: u32 = 1;

/// The line at the top of a lock file that says it is not written by hand.
const HEADER: &str = "# This file is generated by `constructo project update`. Do not edit it.";

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct LockTable {
    version: Spanned<u32>,
    #[serde(default)]
    project: Vec<ProjectTable>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ProjectTable {
    name: Spanned<String>,
    repo: Option<Spanned<String>>,
    commit: Option<Spanned<String>>,
    subdir: Option<Spanned<String>>,
    digest: Spanned<String>,
    files: BTreeMap<String, Spanned<String>>,
}

/// A digest, with where it is written in the lock file. A digest that was not read from a file has the position 1:1.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Recorded {
    pub digest: String,
    pub pos: Pos,
}

/// Where a project that was fetched from a git repository came from: the repository, the commit that was found and the
/// folder in the repository that holds the project, if it is not the root of it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedRemote {
    pub repo: String,
    pub commit: String,
    pub subdir: Option<String>,
}

impl LockedRemote {
    /// The remote as a person would say it, such as `https://example.com/lib.git at 9f2c...`, with the folder if any.
    pub fn describe(&self) -> String {
        match &self.subdir {
            Some(subdir) => format!("{} at {} in {}", self.repo, self.commit, subdir),
            None => format!("{} at {}", self.repo, self.commit),
        }
    }
}

/// The entry for one project.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedProject {
    pub name: String,
    /// The position of the name, which is where the entry starts.
    pub pos: Pos,
    /// Where the project came from if it was fetched, and `None` for one that is a folder on disk.
    pub remote: Option<LockedRemote>,
    pub digest: Recorded,
    /// The digest of each file, keyed by the path inside the project, written with `/`.
    pub files: BTreeMap<String, Recorded>,
}

impl LockedProject {
    /// An entry for a project from the digests of its files, which are pairs of a path and a digest. The digest of the
    /// project is worked out from them.
    pub fn new(name: &str, files: &[(String, String)]) -> LockedProject {
        let at = Pos { line: 1, col: 1 };
        LockedProject {
            name: name.to_string(),
            pos: at,
            remote: None,
            digest: Recorded {
                digest: project_digest(files),
                pos: at,
            },
            files: files
                .iter()
                .map(|(path, digest)| {
                    (
                        path.clone(),
                        Recorded {
                            digest: digest.clone(),
                            pos: at,
                        },
                    )
                })
                .collect(),
        }
    }
}

/// The contents of a lock file.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Lock {
    /// The projects in the order of the file, which is the order of their names when the file was written by this tool.
    pub projects: Vec<LockedProject>,
}

impl Lock {
    /// Makes a lock from entries. The entries are sorted by the name of the project.
    pub fn new(mut projects: Vec<LockedProject>) -> Lock {
        projects.sort_by(|a, b| a.name.cmp(&b.name));
        Lock { projects }
    }

    /// The entry for the project with the name, if there is one.
    pub fn get(&self, name: &str) -> Option<&LockedProject> {
        self.projects.iter().find(|project| project.name == name)
    }

    /// Reads the text of a lock file. `file` is the name of the file in diagnostics. The file is strict: an unknown
    /// key, a value of the wrong type, a digest that is not well-formed, a duplicate project and a project whose digest
    /// is not that of its files are all errors, with the position of the value.
    pub fn parse(text: &str, file: &str) -> Result<Lock, Diagnostic> {
        let text = crate::lexer::strip_bom(text);
        let at = |offset: usize| Pos::at(text, offset);
        let invalid = |offset: usize, message: String| Diagnostic::new(file, at(offset), message);
        let table: LockTable = toml::from_str(text)
            .map_err(|e| invalid(e.span().map_or(0, |span| span.start), e.message().to_string()))?;
        if *table.version.get_ref() != VERSION {
            let message = format!(
                "Unsupported lock file version {}; this version of constructo reads version {}",
                table.version.get_ref(),
                VERSION
            );
            return Err(invalid(table.version.span().start, message));
        }
        let mut projects: Vec<LockedProject> = Vec::new();
        for entry in table.project {
            let name = entry.name.get_ref();
            let start = entry.name.span().start;
            if let Err(reason) = check_name(name) {
                return Err(invalid(start, format!("Invalid project name \"{}\": {}", name, reason)));
            }
            if projects.iter().any(|earlier| &earlier.name == name) {
                return Err(invalid(
                    start,
                    format!("The project {} is in the lock file twice", name),
                ));
            }
            let remote = match (&entry.repo, &entry.commit, &entry.subdir) {
                (None, None, None) => None,
                (Some(repo), Some(commit), subdir) => {
                    if let Err(reason) = validate_url(repo.get_ref()) {
                        let message = format!("Invalid repository \"{}\": {}", redact(repo.get_ref()), reason);
                        return Err(invalid(repo.span().start, message));
                    }
                    if !is_commit(commit.get_ref()) {
                        let message = format!(
                            "Invalid commit \"{}\": it should be 40 lowercase hexadecimal digits",
                            commit.get_ref()
                        );
                        return Err(invalid(commit.span().start, message));
                    }
                    if let Some(subdir) = subdir {
                        if let Err(reason) = check_path(subdir.get_ref()) {
                            let message = format!("Invalid subdir \"{}\": {}", subdir.get_ref(), reason);
                            return Err(invalid(subdir.span().start, message));
                        }
                    }
                    Some(LockedRemote {
                        repo: repo.get_ref().clone(),
                        commit: commit.get_ref().clone(),
                        subdir: subdir.as_ref().map(|subdir| subdir.get_ref().clone()),
                    })
                }
                _ => {
                    let message = format!(
                        "The project {} needs both `repo` and `commit`, or neither, and a `subdir` needs them",
                        name
                    );
                    return Err(invalid(start, message));
                }
            };
            let digest = entry.digest.get_ref();
            if !is_digest(digest) {
                return Err(invalid(
                    entry.digest.span().start,
                    format!(
                        "Invalid digest \"{}\": it should be sha256: and 64 lowercase hexadecimal digits",
                        digest
                    ),
                ));
            }
            let mut files = BTreeMap::new();
            for (path, recorded) in entry.files {
                if let Err(reason) = check_path(&path) {
                    return Err(invalid(
                        recorded.span().start,
                        format!("Invalid file path \"{}\": {}", path, reason),
                    ));
                }
                if !is_digest(recorded.get_ref()) {
                    return Err(invalid(
                        recorded.span().start,
                        format!(
                            "Invalid digest \"{}\": it should be sha256: and 64 lowercase hexadecimal digits",
                            recorded.get_ref()
                        ),
                    ));
                }
                files.insert(
                    path,
                    Recorded {
                        digest: recorded.get_ref().clone(),
                        pos: at(recorded.span().start),
                    },
                );
            }
            // The project digest is worked out from the digests of the files, so a hand-edited file would otherwise
            // report a mismatch for a file that has not changed. This is a defensive check on the file itself.
            let pairs: Vec<(String, String)> = files
                .iter()
                .map(|(path, recorded)| (path.clone(), recorded.digest.clone()))
                .collect();
            if project_digest(&pairs) != *digest {
                let message = format!(
                    "The digest of project {} is not the digest of its files; the lock file was edited",
                    name
                );
                return Err(invalid(entry.digest.span().start, message));
            }
            projects.push(LockedProject {
                name: name.clone(),
                pos: at(start),
                remote,
                digest: Recorded {
                    digest: digest.clone(),
                    pos: at(entry.digest.span().start),
                },
                files,
            });
        }
        Ok(Lock { projects })
    }

    /// The text of the lock file. The projects are in order of name and the files in order of path, so the text does
    /// not change unless the content does.
    pub fn render(&self) -> String {
        let mut sorted: Vec<&LockedProject> = self.projects.iter().collect();
        sorted.sort_by(|a, b| a.name.cmp(&b.name));
        let mut out = format!("{}\nversion = {}\n", HEADER, VERSION);
        for project in sorted {
            out.push_str(&format!("\n[[project]]\nname = {}\n", quote(&project.name)));
            if let Some(remote) = &project.remote {
                out.push_str(&format!(
                    "repo = {}\ncommit = {}\n",
                    quote(&remote.repo),
                    quote(&remote.commit)
                ));
                if let Some(subdir) = &remote.subdir {
                    out.push_str(&format!("subdir = {}\n", quote(subdir)));
                }
            }
            out.push_str(&format!(
                "digest = {}\n\n[project.files]\n",
                quote(&project.digest.digest)
            ));
            // A `BTreeMap` of strings is ordered by the bytes of the paths, which is the order that the digest uses.
            for (path, recorded) in &project.files {
                out.push_str(&format!("{} = {}\n", quote(path), quote(&recorded.digest)));
            }
        }
        out
    }
}

/// Checks that a path is one that can be a path inside a project: relative, written with `/` and with no empty part,
/// `.` or `..`. The reason is returned if it is not valid. It could not be a file of the project otherwise, and a path
/// that leaves the folder would let a lock file name a file elsewhere.
pub(crate) fn check_path(path: &str) -> Result<(), String> {
    if path.is_empty() {
        return Err("it is empty".to_string());
    }
    if path.contains('\\') {
        return Err("it has '\\', but a path is written with '/'".to_string());
    }
    if path
        .split('/')
        .any(|part| part.is_empty() || part == "." || part == "..")
    {
        return Err("it must be relative to the project, with no empty part, '.' or '..'".to_string());
    }
    Ok(())
}

/// A string as a TOML basic string.
fn quote(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::digest::file_digest;

    /// The lock file of the worked example in `docs/specs/lock-file-format.md`.
    const EXAMPLE: &str = "# This file is generated by `constructo project update`. Do not edit it.
version = 1

[[project]]
name = \"com.example.lib\"
digest = \"sha256:753517eedcd17f9bae3699b7e6b2a1be5f91f4e382a3d80de5f0f59ebdc5b163\"

[project.files]
\"constructo.toml\" = \"sha256:1cfdac805747c77556236b673fc4fb71a344aa39d1f8dfdb37bf53fbfae70830\"
\"shapes/circle.types\" = \"sha256:1b0ecdd124592b686f69f8d4544f644fa34b2732bdb94e0500eda45c77025346\"
";

    fn error(text: &str) -> (u32, u32, String) {
        let d = Lock::parse(text, "constructo.lock").unwrap_err();
        assert_eq!(d.file, "constructo.lock");
        (d.pos.line, d.pos.col, d.message)
    }

    #[test]
    fn the_example_of_the_spec_is_read() {
        let lock = Lock::parse(EXAMPLE, "constructo.lock").unwrap();
        assert_eq!(lock.projects.len(), 1);
        let project = lock.get("com.example.lib").unwrap();
        assert_eq!(project.pos, Pos { line: 5, col: 8 });
        assert_eq!(project.digest.pos, Pos { line: 6, col: 10 });
        let paths: Vec<&str> = project.files.keys().map(|p| p.as_str()).collect();
        assert_eq!(paths, ["constructo.toml", "shapes/circle.types"]);
        // The position of a file is that of its digest.
        assert_eq!(project.files["shapes/circle.types"].pos, Pos { line: 10, col: 25 });
        assert!(lock.get("com.example.other").is_none());
    }

    #[test]
    fn a_lock_is_written_as_it_was_read() {
        let lock = Lock::parse(EXAMPLE, "constructo.lock").unwrap();
        assert_eq!(lock.render(), EXAMPLE);
    }

    #[test]
    fn a_lock_made_from_digests_is_written_in_order() {
        let entry = |name: &str, contents: &[(&str, &str)]| {
            let files: Vec<(String, String)> = contents
                .iter()
                .map(|(path, text)| (path.to_string(), file_digest(text.as_bytes())))
                .collect();
            LockedProject::new(name, &files)
        };
        let lock = Lock::new(vec![
            entry(
                "z.last",
                &[("constructo.toml", "z"), ("b.types", "b"), ("a.types", "a")],
            ),
            entry("a.first", &[("constructo.toml", "a")]),
        ]);
        let text = lock.render();
        // The projects are sorted by name and the files by path.
        assert!(text.find("a.first").unwrap() < text.find("z.last").unwrap());
        let last = &text[text.find("z.last").unwrap()..];
        let order: Vec<usize> = ["\"a.types\"", "\"b.types\"", "\"constructo.toml\""]
            .iter()
            .map(|path| last.find(path).unwrap())
            .collect();
        assert!(order[0] < order[1] && order[1] < order[2], "{}", text);
        // What is written can be read, and means the same.
        let read = Lock::parse(&text, "constructo.lock").unwrap();
        assert_eq!(read.render(), text);
        let names: Vec<&str> = read.projects.iter().map(|p| p.name.as_str()).collect();
        assert_eq!(names, ["a.first", "z.last"]);
    }

    #[test]
    fn a_lock_with_no_projects_is_read_and_written() {
        let text = format!("{}\nversion = 1\n", HEADER);
        let lock = Lock::parse(&text, "constructo.lock").unwrap();
        assert!(lock.projects.is_empty());
        assert_eq!(lock.render(), text);
        // The header is a comment, so it is not needed.
        assert!(Lock::parse("version = 1\n", "constructo.lock").is_ok());
    }

    #[test]
    fn a_byte_order_mark_is_not_a_part_of_the_file() {
        let with = format!("\u{feff}{}", EXAMPLE);
        assert_eq!(
            Lock::parse(&with, "c.lock").unwrap(),
            Lock::parse(EXAMPLE, "c.lock").unwrap()
        );
    }

    #[test]
    fn the_version_must_be_there_and_be_1() {
        assert!(error("").2.contains("missing field `version`"));
        let (line, col, message) = error("version = 2\n");
        assert_eq!((line, col), (1, 11));
        assert_eq!(
            message,
            "Unsupported lock file version 2; this version of constructo reads version 1"
        );
        assert!(error("version = \"1\"\n").2.contains("invalid type: string"));
        assert!(error("version = -1\n").2.contains("invalid value"));
    }

    #[test]
    fn the_file_is_strict() {
        assert!(error("version = 1\nother = 1\n").2.contains("unknown field `other`"));
        let with = |entry: &str| format!("version = 1\n\n[[project]]\n{}", entry);
        assert!(error(&with("digest = \"x\"\n[project.files]\n"))
            .2
            .contains("missing field `name`"));
        assert!(error(&with("name = \"a.b\"\n[project.files]\n"))
            .2
            .contains("missing field `digest`"));
        assert!(error(&with("name = \"a.b\"\ndigest = \"x\"\n"))
            .2
            .contains("missing field `files`"));
        assert!(
            error(&with("name = \"a.b\"\ndigest = \"x\"\nextra = 1\n[project.files]\n"))
                .2
                .contains("unknown field `extra`")
        );
        assert!(error(&with("name = 1\ndigest = \"x\"\n[project.files]\n"))
            .2
            .contains("invalid type: integer"));
    }

    #[test]
    fn a_digest_must_be_well_formed() {
        let text = "version = 1\n\n[[project]]\nname = \"a.b\"\ndigest = \"sha256:abc\"\n\n[project.files]\n";
        let (line, col, message) = error(text);
        assert_eq!((line, col), (5, 10));
        assert!(message.starts_with("Invalid digest \"sha256:abc\""), "{}", message);
        let digest = "sha256:753517eedcd17f9bae3699b7e6b2a1be5f91f4e382a3d80de5f0f59ebdc5b163";
        let text = format!(
            "version = 1\n\n[[project]]\nname = \"a.b\"\ndigest = \"{}\"\n\n{}",
            digest, "[project.files]\n\"constructo.toml\" = \"md5:00\"\n"
        );
        let (line, col, message) = error(&text);
        assert_eq!((line, col), (8, 21));
        assert!(message.starts_with("Invalid digest \"md5:00\""), "{}", message);
    }

    #[test]
    fn a_project_name_must_follow_the_rule_and_be_there_once() {
        let digest = crate::digest::project_digest(&[]);
        let entry = |name: &str| {
            format!(
                "\n[[project]]\nname = \"{}\"\ndigest = \"{}\"\n[project.files]\n",
                name, digest
            )
        };
        let (line, col, message) = error(&format!("version = 1\n{}", entry("lib")));
        assert_eq!((line, col), (4, 8));
        assert!(message.starts_with("Invalid project name \"lib\""), "{}", message);
        let (line, col, message) = error(&format!("version = 1\n{}{}", entry("a.b"), entry("a.b")));
        assert_eq!((line, col), (9, 8));
        assert_eq!(message, "The project a.b is in the lock file twice");
    }

    #[test]
    fn the_digest_of_a_project_must_be_that_of_its_files() {
        // The file digest is changed in the example, so the digest of the project is no longer the one for its files.
        let edited = EXAMPLE.replace("1b0ecdd1", "2b0ecdd1");
        let (line, col, message) = error(&edited);
        assert_eq!((line, col), (6, 10));
        assert_eq!(
            message,
            "The digest of project com.example.lib is not the digest of its files; the lock file was edited"
        );
    }

    #[test]
    fn a_path_must_be_one_inside_the_project() {
        for (path, ok) in [
            ("constructo.toml", true),
            ("a/b/c.types", true),
            ("", false),
            ("/a.types", false),
            ("a//b.types", false),
            ("a/", false),
            ("./a.types", false),
            ("../a.types", false),
            ("a/../b.types", false),
            ("a\\b.types", false),
        ] {
            assert_eq!(check_path(path).is_ok(), ok, "{:?}", path);
        }
    }

    #[test]
    fn unusual_characters_in_a_path_survive_a_round_trip() {
        // A quote and a control character are written escaped and read back. A backslash is not allowed in a path.
        let files = vec![("we\"ird\tx.types".to_string(), file_digest(b"x"))];
        let lock = Lock::new(vec![LockedProject::new("a.b", &files)]);
        let read = Lock::parse(&lock.render(), "c.lock").unwrap();
        assert_eq!(read.render(), lock.render());
        assert!(read.get("a.b").unwrap().files.contains_key(&files[0].0));
    }
    #[test]
    fn a_fetched_project_records_where_it_came_from() {
        let files = vec![("constructo.toml".to_string(), file_digest(b"x"))];
        let mut entry = LockedProject::new("example.lib", &files);
        let commit = "ab".repeat(20);
        entry.remote = Some(LockedRemote {
            repo: "https://example.com/lib.git".to_string(),
            commit: commit.clone(),
            subdir: Some("shapes".to_string()),
        });
        let text = Lock::new(vec![entry.clone()]).render();
        assert!(
            text.contains(&format!(
                "name = \"example.lib\"\nrepo = \"https://example.com/lib.git\"\ncommit = \"{}\"\nsubdir = \"shapes\"\ndigest",
                commit
            )),
            "{}",
            text
        );
        let again = Lock::parse(&text, "constructo.lock").unwrap();
        assert_eq!(again.get("example.lib").unwrap().remote, entry.remote);
        assert_eq!(again.render(), text);
    }

    #[test]
    fn the_remote_of_a_project_is_strict() {
        let files = vec![("constructo.toml".to_string(), file_digest(b"x"))];
        let entry = LockedProject::new("example.lib", &files);
        let good = Lock::new(vec![entry]).render();
        let with = |extra: &str| good.replacen("digest =", &format!("{}digest =", extra), 1);
        let commit = "ab".repeat(20);
        let err = |text: String| Lock::parse(&text, "constructo.lock").unwrap_err().to_string();
        assert!(err(with("repo = \"https://example.com/lib\"\n")).contains("both `repo` and `commit`"));
        assert!(err(with(&format!("commit = \"{}\"\n", commit))).contains("both `repo` and `commit`"));
        assert!(err(with(&format!("subdir = \"a\"\ncommit = \"{}\"\n", commit))).contains("both `repo` and `commit`"));
        assert!(err(with(&format!("repo = \"ext::ls\"\ncommit = \"{}\"\n", commit))).contains("Invalid repository"));
        assert!(err(with("repo = \"/r\"\ncommit = \"abc\"\n")).contains("Invalid commit"));
        assert!(err(with(&format!(
            "repo = \"/r\"\ncommit = \"{}\"\nsubdir = \"../a\"\n",
            commit
        )))
        .contains("Invalid subdir"));
    }
}

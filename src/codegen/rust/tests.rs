use super::*;
use crate::resolve::{ImportInfo, Layout, ProjectInfo};
use crate::{build_model, prelude_source, CheckOptions, Source};

/// The Rust of the prelude and the projects, each with its full name, its imports other than the prelude, which every
/// project imports into `local`, and its types. The projects are numbered from 1, and the last is the root.
fn rust_of(projects: &[(&str, Vec<ImportInfo>, &str)]) -> Generated {
    let mut infos = vec![ProjectInfo {
        name: crate::PRELUDE_PROJECT.to_string(),
        imports: Vec::new(),
        builtin: true,
    }];
    let mut sources = vec![prelude_source()];
    for (name, imports, text) in projects {
        let mut all = vec![ImportInfo::new(Some("local"), 0)];
        all.extend(imports.iter().cloned());
        infos.push(ProjectInfo {
            name: name.to_string(),
            imports: all,
            builtin: false,
        });
        sources.push(Source {
            name: format!("{}.types", name),
            text: text.to_string(),
        });
    }
    let layout = Layout {
        projects: infos,
        owners: (0..sources.len()).collect(),
        root: projects.len(),
    };
    let model = build_model(&sources, &layout, &CheckOptions::default())
        .unwrap_or_else(|found| panic!("{:?}", found.iter().map(|d| d.to_string()).collect::<Vec<_>>()));
    generate(&model).unwrap_or_else(|found| panic!("{:?}", found.iter().map(|d| d.to_string()).collect::<Vec<_>>()))
}

/// The Rust of one project, `example.app`.
fn rust(text: &str) -> Generated {
    rust_of(&[("example.app", vec![], text)])
}

/// The warnings, as they are shown.
fn warnings(generated: &Generated) -> Vec<String> {
    generated.warnings.iter().map(|w| w.to_string()).collect()
}

/// Asserts that the text has every line, in order, though not necessarily together.
#[track_caller]
fn assert_lines(generated: &Generated, expected: &[&str]) {
    let mut lines = generated.text.lines();
    for line in expected {
        assert!(
            lines.any(|found| found == *line),
            "no line {:?} in order in:\n{}",
            line,
            generated.text
        );
    }
}

#[test]
fn the_file_has_a_header_and_the_root_has_no_module() {
    let generated = rust("enum Colour = Red, Green;");
    assert!(generated.text.starts_with(
        "//! Generated by constructo codegen from the project example.app. Do not edit.\n\
         #![allow(non_camel_case_types, non_snake_case, dead_code, clippy::all)]\n"
    ));
    assert!(!generated.text.contains("mod "), "{}", generated.text);
    assert!(generated.warnings.is_empty());
}

#[test]
fn an_enum_of_several_constructors_has_a_struct_for_each_with_a_body() {
    let generated = rust(
        "enum Shape = Circle { radius: Float }, Box { width: Float, height: Float }, Dot, Polygon[Point], \
         Pair(Nat, String), Ping();
         enum Point = Point(x: Float, y: Float);",
    );
    assert_lines(
        &generated,
        &[
            "/// The enum `example.app::Shape`.",
            "#[derive(Debug, Clone, PartialEq)]",
            "pub enum Shape {",
            "    Circle(self::Circle),",
            "    Box(self::Box),",
            "    Dot,",
            "    Polygon(self::Polygon),",
            "    Pair(self::Pair),",
            "    Ping(self::Ping),",
            "}",
            "/// The constructor `example.app::Circle`.",
            "pub struct Circle {",
            "    pub radius: ::std::primitive::f64,",
            "}",
            "pub struct Box {",
            "    pub width: ::std::primitive::f64,",
            "    pub height: ::std::primitive::f64,",
            "}",
            "pub struct Polygon(pub ::std::vec::Vec<self::Point>);",
            "pub struct Pair(pub ::std::primitive::u64, pub ::std::string::String);",
            "pub struct Ping();",
        ],
    );
}

#[test]
fn an_enum_of_one_constructor_is_one_struct_named_after_the_enum() {
    let generated = rust(
        "enum Point = Point(x: Float, y: Float);
         enum Temperature = Celsius(Float);
         enum Unit = Unit;
         enum Empty = Empty {};
         enum Users = Users[String];",
    );
    assert_lines(
        &generated,
        &[
            "/// The enum `example.app::Point`, of one constructor, `Point`.",
            "pub struct Point {",
            "    pub x: ::std::primitive::f64,",
            "    pub y: ::std::primitive::f64,",
            "}",
            "pub struct Temperature(pub ::std::primitive::f64);",
            "pub struct Unit;",
            "pub struct Empty {}",
            "pub struct Users(pub ::std::vec::Vec<::std::string::String>);",
        ],
    );
    assert!(!generated.text.contains("enum Point"));
}

#[test]
fn a_parameter_without_a_name_is_named_by_its_position() {
    let generated = rust("enum B = B(Nat, String, y: Nat, _0: Bool);");
    assert_lines(
        &generated,
        &[
            "pub struct B {",
            "    pub _0: ::std::primitive::u64,",
            "    pub _1: ::std::string::String,",
            "    pub y: ::std::primitive::u64,",
            "    pub _0_: ::std::primitive::bool,",
            "}",
        ],
    );
    assert_eq!(
        warnings(&generated),
        [
            "WARNING: The field _0 of example.app::B is _0_ in Rust, since _0 names a parameter that has no name \
          (example.app.types, line 1, col 33)"
        ]
    );
}


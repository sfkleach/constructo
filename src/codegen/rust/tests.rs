/// The errors of the Rust of one project, `example.app`, which Rust cannot hold.
fn refused(text: &str) -> Vec<String> {
    let sources = vec![
        prelude_source(),
        Source {
            name: "app.types".into(),
            text: text.into(),
        },
    ];
    let layout = crate::plain_layout(&sources);
    let model = build_model(&sources, &layout, &CheckOptions::default()).unwrap();
    generate(&model, &Defaults::default(), &Adoptions::default())
        .expect_err("Rust cannot hold the types")
        .iter()
        .map(|d| d.to_string())
        .collect()
}

#[test]
fn a_type_that_holds_itself_with_other_arguments_is_refused() {
    assert_eq!(
        refused("enum Nested<T> = Flat(T), Deep(Nested<[T]>);"),
        [
            "ERROR: Rust cannot hold the enum Nested, since it holds itself with other arguments \
          (app.types, line 1, col 6)"
        ]
    );
    // Through an array, which Rust's drop-check follows as it does a `Box`.
    assert_eq!(refused("enum T<A> = L(A), N([T<[A]>]);").len(), 1);
    // Through another enum and a record.
    assert_eq!(
        refused("enum A<T> = A(B<T>), Stop; enum B<U> = B { r: { next: A<{ u: U }> } };"),
        [
            "ERROR: Rust cannot hold the record type next, since it holds the enum A with other arguments than it is \
          held with (app.types, line 1, col 49)"
        ]
    );
}

#[test]
fn a_type_that_holds_itself_with_the_same_arguments_or_another_type_with_others_is_not_refused() {
    let generated = rust(
        "enum List<T> = Nil, Cons { head: T, tail: List<T> };
         enum Pair<A, B> = Pair(A, B);
         enum Swap<A, B> = End, Swap(Swap<A, B>, Pair<B, A>);
         enum Uses<T> = Uses(Pair<T, Nat>, Pair<Nat, T>, List<T>, List<[T]>);",
    );
    // Nothing is refused, and `List<[T]>` is another type than the `List<T>` of the cycle, so it is no error.
    assert!(generated.text.contains("pub enum Swap<A, B> {") && generated.text.contains("pub struct Uses<T>("));
}


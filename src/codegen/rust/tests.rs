#[test]
fn a_constructor_called_like_an_enum_takes_the_name_of_its_own_enum_in_front() {
    let generated = rust(
        "enum Circle = Round(Float);
         enum Shape = Circle { r: Float }, Square(Float);
         enum ShapeSquare = X;
         enum Other = Square2, ShapeSquare(Nat), Spare;",
    );
    assert_lines(
        &generated,
        &[
            "pub struct Circle(pub ::std::primitive::f64);",
            "pub enum Shape {",
            "    Circle(self::ShapeCircle),",
            "    Square(self::Square),",
            "pub struct ShapeCircle {",
        ],
    );
    assert_lines(
        &generated,
        &["pub enum Other {", "    ShapeSquare(self::OtherShapeSquare),"],
    );
    assert_eq!(
        warnings(&generated),
        [
            "WARNING: The constructor example.app::Circle is ShapeCircle in Rust, since the enum Circle has its name \
             (example.app.types, line 2, col 23)",
            "WARNING: The constructor example.app::ShapeSquare is OtherShapeSquare in Rust, since the enum \
             ShapeSquare has its name (example.app.types, line 4, col 32)",
        ]
    );
}


#[test]
fn a_const_whose_value_rust_cannot_hold_is_refused() {
    assert_eq!(
        refused("const big: Nat = 99999999999999999999999;"),
        [
            "ERROR: Rust cannot hold the value of the const big: The number 99999999999999999999999 does not fit Nat \
          (app.types, line 1, col 7)"
        ]
    );
    // Inside a value, widened, and through a generic type whose argument is known.
    let errors = refused(
        "enum P<T> = P(T, y: Int);
         const a: [P<Nat>] = [P(1, y: 9223372036854775808)];
         const b: Float? = Some(1.0e400);
         const c: P<Float> = P(-9.0e999, y: 1);
         const fine: P<Nat> = P(18446744073709551615, y: -9223372036854775808);",
    );
    let messages: Vec<&str> = errors
        .iter()
        .map(|e| e.split(": ").nth(2).unwrap_or(e).split(" (").next().unwrap_or(e))
        .collect();
    assert_eq!(
        messages,
        [
            "The number 9223372036854775808 does not fit Int",
            "The number 1.0e400 does not fit Float",
            "The number -9.0e999 does not fit Float",
        ]
    );
}

/// The Rust of types files without a project, with the adoptions of the file's text, which are checked first.
fn adopted(types: &str, adoptions: &str) -> Result<Generated, Vec<String>> {
    let sources = vec![
        prelude_source(),
        Source {
            name: "app.types".into(),
            text: types.into(),
        },
    ];
    let layout = crate::plain_layout(&sources);
    let model = build_model(&sources, &layout, &CheckOptions::default()).unwrap();
    let adoptions = Adoptions::parse(adoptions, "adopt.toml").unwrap();
    assert_eq!(adoptions.check(&model), Vec::new());
    generate(&model, &Defaults::default(), &adoptions).map_err(|found| found.iter().map(|d| d.to_string()).collect())
}

/// A table of the file of adoptions, for a constructor or an enum.
fn adopt(kind: &str, name: &str) -> String {
    format!(
        "[rust.{}.\"{}\"]\ntype = \"crate::{}\"\nfrom = \"crate::from\"\nto = \"crate::to\"\n",
        kind, name, name
    )
}

#[test]
fn an_adopted_type_breaks_a_cycle_so_that_nothing_on_it_is_boxed() {
    let types = "enum Expr = Num(Nat), Neg(Term); enum Term = Lit(Nat), Paren(Expr);";
    let boxed = "pub struct Neg(pub ::std::boxed::Box<self::Term>);";
    assert!(adopted(types, "").unwrap().text.contains(boxed));
    // The constructor that closes the cycle holds nothing that the generator can see, so the other is not boxed.
    let generated = adopted(types, &adopt("constructor", "Paren")).unwrap();
    assert_lines(&generated, &["pub struct Neg(pub self::Term);"]);
    // An enum adopted whole is not seen into at any use, so neither field is on a cycle.
    let generated = adopted(types, &adopt("enum", "Term")).unwrap();
    assert_lines(
        &generated,
        &["pub struct Neg(pub crate::Term);", "pub struct Paren(pub self::Expr);"],
    );
}


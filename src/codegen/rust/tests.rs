/// The Rust of the prelude and the projects, each with its full name, its imports other than the prelude, which every
/// project imports into `local`, and its types. The projects are numbered from 1, and the last is the root.
fn rust_of(projects: &[(&str, Vec<ImportInfo>, &str)]) -> Generated {
    let mut infos = vec![ProjectInfo {
        name: crate::PRELUDE_PROJECT.to_string(),
        imports: Vec::new(),
        builtin: true,
    }];
    let mut sources = vec![prelude_source()];
    for (name, imports, text) in projects {
        let mut all = vec![ImportInfo::new(Some("local"), 0)];
        all.extend(imports.iter().cloned());
        infos.push(ProjectInfo {
            name: name.to_string(),
            imports: all,
            builtin: false,
        });
        sources.push(Source {
            name: format!("{}.types", name),
            text: text.to_string(),
        });
    }
    let layout = Layout {
        projects: infos,
        owners: (0..sources.len()).collect(),
        root: projects.len(),
    };
    let model = build_model(&sources, &layout, &CheckOptions::default())
        .unwrap_or_else(|found| panic!("{:?}", found.iter().map(|d| d.to_string()).collect::<Vec<_>>()));
    generate(&model, &Defaults::default(), &Adoptions::default())
        .unwrap_or_else(|found| panic!("{:?}", found.iter().map(|d| d.to_string()).collect::<Vec<_>>()))
}

/// The Rust of one project, `example.app`.
fn rust(text: &str) -> Generated {
    rust_of(&[("example.app", vec![], text)])
}

/// The warnings, as they are shown.
fn warnings(generated: &Generated) -> Vec<String> {
    generated.warnings.iter().map(|w| w.to_string()).collect()
}

/// Asserts that the text has every line, in order, though not necessarily together.
#[track_caller]
fn assert_lines(generated: &Generated, expected: &[&str]) {
    let mut lines = generated.text.lines();
    for line in expected {
        assert!(
            lines.any(|found| found == *line),
            "no line {:?} in order in:\n{}",
            line,
            generated.text
        );
    }
}

#[test]
fn the_file_has_a_header_and_the_root_has_no_module() {
    let generated = rust("enum Colour = Red, Green;");
    let version = format!(
        "{}.{}",
        env!("CARGO_PKG_VERSION_MAJOR"),
        env!("CARGO_PKG_VERSION_MINOR")
    );
    assert!(generated.text.starts_with(&format!(
        "//! Generated by constructo codegen from the project example.app. Do not edit.\n\
         //! It needs the crate constructo-runtime {}.\n\
         #![allow(non_camel_case_types, non_snake_case, dead_code, clippy::all)]\n",
        version
    )));
    assert!(!generated.text.contains("mod "), "{}", generated.text);
    assert!(generated.warnings.is_empty());
}


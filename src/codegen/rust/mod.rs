use std::collections::HashMap;

/// The file that is generated, and the warnings for the names that it had to change.
#[derive(Debug, Clone, PartialEq)]
pub struct Generated {
    pub text: String,
    pub warnings: Vec<Diagnostic>,
}

/// Writes the Rust types of the model and their codec, whose settings have the defaults given, with the adoptions,
/// which have been checked against the model, or gives the errors for the types and the consts that Rust cannot hold,
/// which are at their declarations.
pub fn generate(model: &Model, defaults: &Defaults, adoptions: &Adoptions) -> Result<Generated, Vec<Diagnostic>> {
    // An adopted type is opaque, so a cycle through it is no cycle of the generated types, which are boxed again.
    let opaque = adoptions.opaque(model);
    let mut model = model.clone();
    super::recursion::rebox(&mut model, &opaque);
    let model = &model;
    let names = Names::new(model);
    let mut errors = regular::irregular(model, &names.index, &opaque);
    errors.extend(codec::const_errors(model, &names.index));
    if !errors.is_empty() {
        return Err(errors);
    }
    let writer = Writer { model, names: &names };
    let mut text = String::new();
    let root = &model.projects[model.root];
    if root.name.is_empty() {
        text.push_str("//! Generated by constructo codegen from types files. Do not edit.\n");
    } else {
        text.push_str(&format!(
            "//! Generated by constructo codegen from the project {}. Do not edit.\n",
            root.name
        ));
    }
    text.push_str(&format!(
        "//! It needs the crate constructo-runtime {}.\n",
        RUNTIME_VERSION
    ));
    text.push_str("#![allow(non_camel_case_types, non_snake_case, dead_code, clippy::all)]\n");
    for line in writer
        .module(model.root)
        .into_iter()
        .chain(writer.codec(defaults))
        .chain(writer.impls(model.root))
    {
        push_line(&mut text, &line, 0);
    }
    for (project, info) in model.projects.iter().enumerate() {
        let Some(module) = &names.modules[project] else {
            continue;
        };
        text.push('\n');
        text.push_str(&format!("/// The project `{}`.\n", info.name));
        text.push_str(&format!("pub mod {} {{\n", module));
        for line in writer.module(project).into_iter().chain(writer.impls(project)) {
            push_line(&mut text, &line, 1);
        }
        text.push_str("}\n");
    }
    // The warnings are made a kind at a time, and are given in the order of the files and the places in them.
    let order = |file: &str| model.files.iter().position(|f| f == file).unwrap_or(model.files.len());
    let mut warnings = names.warnings.clone();
    warnings.sort_by_key(|w| (order(&w.file), w.pos));
    Ok(Generated { text, warnings })
}

/// The version of `constructo-runtime` that the generated code needs, as its major and minor numbers, which is that of
/// `constructo`, since the two are released together. A version before 1.0 is compatible with those of the same minor
/// number, so the file names no more, and changes only when a release could change what it needs.
const RUNTIME_VERSION: &str = concat!(env!("CARGO_PKG_VERSION_MAJOR"), ".", env!("CARGO_PKG_VERSION_MINOR"));

/// Adds a line at the level of indentation, leaving an empty line empty.
fn push_line(text: &mut String, line: &str, level: usize) {
    if !line.is_empty() {
        text.push_str(&"    ".repeat(level));
        text.push_str(line);
    }
    text.push('\n');
}

struct Writer<'m> {
    model: &'m Model,
    names: &'m Names,
}

impl Writer<'_> {
    /// The lines of the module of a project: its enums, and the records that it uses, each after an empty line.
    fn module(&self, project: usize) -> Vec<String> {
        let mut lines = Vec::new();
        for (at, decl) in self.model.enums.iter().enumerate() {
            if decl.project == project && !is_rusts_own(&decl.name) {
                self.enum_items(at, decl, &mut lines);
            }
        }
        for (at, record) in self.model.records.iter().enumerate() {
            if record.projects.contains(&project) {
                self.record_item(at, record, project, &mut lines);
            }
        }
        lines
    }

    /// The Rust items of an enum: one `struct` if it has one constructor, and otherwise an `enum` with the `struct` of
    /// each constructor that has a body.
    fn enum_items(&self, at: usize, decl: &Enum, lines: &mut Vec<String>) {
        let params = &self.names.params[at];
        let kept = &self.names.kept[at];
        let rename: HashMap<&str, &str> = decl
            .params
            .iter()
            .zip(params)
            .map(|(param, rust)| (param.name.as_str(), rust.as_str()))
            .collect();
        let generics = |keep: &dyn Fn(usize) -> bool| {
            generic_list(
                params
                    .iter()
                    .enumerate()
                    .filter(|&(p, _)| keep(p))
                    .map(|(_, name)| name.clone()),
            )
        };
        let name = &self.names.types[at];
        lines.push(String::new());
        if let [constructor] = &decl.constructors[..] {
            lines.push(format!(
                "/// The enum `{}`, of one constructor, `{}`.",
                decl.name, constructor.name.local
            ));
            let generics = generics(&|p| kept[p]);
            let fields = &self.names.fields[at][0];
            self.struct_item(name, &generics, &constructor.body, fields, decl.project, &rename, lines);
            return;
        }
        lines.push(format!("/// The enum `{}`.", decl.name));
        lines.push("#[derive(Debug, Clone, PartialEq)]".to_string());
        lines.push(format!("pub enum {}{} {{", name, generics(&|p| kept[p])));
        let mut structs = Vec::new();
        for (c, constructor) in decl.constructors.iter().enumerate() {
            let variant = &self.names.variants[at][c];
            match &self.names.structs[at][c] {
                None => lines.push(format!("    {},", variant)),
                Some(rust) => {
                    // The `struct` has the parameters of the enum that its body holds, in the enum's order.
                    let holds = |p: usize| {
                        kept[p]
                            && body_types(&constructor.body).iter().any(|ty| {
                                occurs(
                                    ty,
                                    &decl.params[p].name,
                                    &self.names.kept,
                                    &self.names.kept_records,
                                    &self.names.index,
                                )
                            })
                    };
                    let generics = generics(&holds);
                    lines.push(format!("    {}(self::{}{}),", variant, rust, generics));
                    structs.push((c, rust, generics));
                }
            }
        }
        lines.push("}".to_string());
        for (c, rust, generics) in structs {
            let constructor = &decl.constructors[c];
            lines.push(String::new());
            lines.push(format!("/// The constructor `{}`.", constructor.name));
            let fields = &self.names.fields[at][c];
            self.struct_item(rust, &generics, &constructor.body, fields, decl.project, &rename, lines);
        }
    }

    /// A `struct` with the body of a constructor.
    #[allow(clippy::too_many_arguments)]
    fn struct_item(
        &self,
        name: &str,
        generics: &str,
        body: &Body,
        fields: &Fields,
        project: usize,
        rename: &HashMap<&str, &str>,
        lines: &mut Vec<String>,
    ) {
        lines.push("#[derive(Debug, Clone, PartialEq)]".to_string());
        let ty = |ty: &TypeRef, boxed: bool| self.field_type(ty, boxed, project, rename);
        match (body, fields) {
            (Body::None, _) => lines.push(format!("pub struct {}{};", name, generics)),
            (Body::Array(element), _) => lines.push(format!(
                "pub struct {}{}(pub ::std::vec::Vec<{}>);",
                name,
                generics,
                ty(element, false)
            )),
            (Body::Tuple(parameters), Fields::Tuple) => {
                let parts: Vec<String> = parameters
                    .iter()
                    .map(|p| format!("pub {}", ty(&p.ty, p.boxed)))
                    .collect();
                lines.push(format!("pub struct {}{}({});", name, generics, parts.join(", ")));
            }
            (Body::Tuple(parameters), Fields::Named(names)) => {
                let parts = parameters.iter().map(|p| ty(&p.ty, p.boxed));
                named_struct(name, generics, names.iter().zip(parts), lines);
            }
            (Body::Record(fields), Fields::Named(names)) => {
                let parts = fields.iter().map(|f| ty(&f.ty, f.boxed));
                named_struct(name, generics, names.iter().zip(parts), lines);
            }
            (Body::Record(_), Fields::Tuple) => unreachable!("the fields of a record have names"),
        }
    }

    /// The `struct` of a record type without a name, in the module of a project that uses it.
    fn record_item(&self, at: usize, record: &Record, project: usize, lines: &mut Vec<String>) {
        let kept = &self.names.kept_records[at];
        let generics = generic_list(
            record
                .params
                .iter()
                .enumerate()
                .filter(|&(p, _)| kept[p])
                .map(|(_, name)| name.clone()),
        );
        let field_names: Vec<&str> = record.fields.iter().map(|f| f.name.as_str()).collect();
        lines.push(String::new());
        lines.push(format!(
            "/// The record type without a name whose fields are {}.",
            if field_names.is_empty() {
                "none".to_string()
            } else {
                field_names
                    .iter()
                    .map(|n| format!("`{}`", n))
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        ));
        lines.push("#[derive(Debug, Clone, PartialEq)]".to_string());
        let rename = HashMap::new();
        let parts = record
            .fields
            .iter()
            .map(|f| self.field_type(&f.ty, f.boxed, project, &rename));
        named_struct(
            &self.names.records[at],
            &generics,
            self.names.record_fields[at].iter().zip(parts),
            lines,
        );
    }

    /// The type of a field, in a `Box` if it is boxed. A boxed `Option` has the box inside, as `Option<Box<T>>`.
    fn field_type(&self, ty: &TypeRef, boxed: bool, from: usize, rename: &HashMap<&str, &str>) -> String {
        if !boxed {
            return self.ty(ty, from, rename);
        }
        match ty {
            TypeRef::Enum(name, args) if is_rusts_own(name) && name.local == "Option" => format!(
                "::std::option::Option<{}>",
                self.field_type(&args[0], true, from, rename)
            ),
            _ => format!("::std::boxed::Box<{}>", self.ty(ty, from, rename)),
        }
    }

    /// A type as it is written in the module of the project `from`, where `rename` gives the Rust name of each
    /// parameter that has another.
    fn ty(&self, ty: &TypeRef, from: usize, rename: &HashMap<&str, &str>) -> String {
        let args = |args: &[TypeRef], kept: &[bool]| {
            generic_list(
                args.iter()
                    .zip(kept)
                    .filter(|(_, &keep)| keep)
                    .map(|(arg, _)| self.ty(arg, from, rename)),
            )
        };
        match ty {
            TypeRef::Nat => "::std::primitive::u64".to_string(),
            TypeRef::Int => "::std::primitive::i64".to_string(),
            TypeRef::Float => "::std::primitive::f64".to_string(),
            TypeRef::String => "::std::string::String".to_string(),
            TypeRef::Array(element) => format!("::std::vec::Vec<{}>", self.ty(element, from, rename)),
            TypeRef::Param(name) => rename.get(name.as_str()).copied().unwrap_or(name).to_string(),
            TypeRef::Enum(name, list) if is_rusts_own(name) => match name.local.as_str() {
                "Bool" => "::std::primitive::bool".to_string(),
                _ => format!("::std::option::Option<{}>", self.ty(&list[0], from, rename)),
            },
            TypeRef::Enum(name, list) => {
                let at = self.names.index[name];
                let decl = &self.model.enums[at];
                let path = self.path(from, decl.project, &self.names.types[at]);
                format!("{}{}", path, args(list, &self.names.kept[at]))
            }
            TypeRef::Record(at, list) => format!(
                "self::{}{}",
                self.names.records[*at],
                args(list, &self.names.kept_records[*at])
            ),
        }
    }

    /// The path from the module of the project `from` to the item `name` of the project `to`. The root is the file's
    /// module and every other project is a module in it.
    fn path(&self, from: usize, to: usize, name: &str) -> String {
        let root = self.model.root;
        let module = || {
            self.names.modules[to]
                .as_deref()
                .expect("a project whose types are used has a module")
        };
        if from == to {
            format!("self::{}", name)
        } else if from == root {
            format!("self::{}::{}", module(), name)
        } else if to == root {
            format!("super::{}", name)
        } else {
            format!("super::{}::{}", module(), name)
        }
    }
}

/// `<A, B>`, or nothing if there are none.
fn generic_list(names: impl Iterator<Item = String>) -> String {
    let names: Vec<String> = names.collect();
    if names.is_empty() {
        String::new()
    } else {
        format!("<{}>", names.join(", "))
    }
}

/// A `struct` with named fields, each with its type.
fn named_struct<'a>(
    name: &str,
    generics: &str,
    fields: impl Iterator<Item = (&'a String, String)>,
    lines: &mut Vec<String>,
) {
    let fields: Vec<(&String, String)> = fields.collect();
    if fields.is_empty() {
        lines.push(format!("pub struct {}{} {{}}", name, generics));
        return;
    }
    lines.push(format!("pub struct {}{} {{", name, generics));
    for (field, ty) in fields {
        lines.push(format!("    pub {}: {},", field, ty));
    }
    lines.push("}".to_string());
}

